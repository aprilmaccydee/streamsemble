    /// <summary>The forward S-box, inverted from <see cref="InverseSBox"/> rather than duplicated.</summary>
    internal static readonly byte[] ForwardSBox = BuildForwardSBox();

    private static byte[] BuildForwardSBox()
    {
        var forward = new byte[256];
        for (var plaintext = 0; plaintext < 256; plaintext++)
        {
            forward[InverseSBox[plaintext]] = (byte)plaintext;
        }

        return forward;
    }

