    /// <summary>
    /// MD5's additive constants, computed rather than tabulated: round i adds
    /// floor(|sin(i+1)| * 2^32). Deriving them keeps the source honest about
    /// what they are — there is nothing FairPlay-specific in this table.
    /// </summary>
    internal static readonly uint[] Md5Constant = BuildMd5Constants();

    private static uint[] BuildMd5Constants()
    {
        var constants = new uint[64];
        for (var round = 0; round < constants.Length; round++)
        {
            constants[round] = (uint)(Math.Abs(Math.Sin(round + 1)) * 4294967296.0);
        }

        return constants;
    }
